//! The window's words, in English and French. Written for anyone, not only cabinet
//! builders: plain words, and the jargon explained where it cannot be avoided.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    En,
    Fr,
}

impl Lang {
    /// The system's language, when it is French; English otherwise.
    pub fn from_system() -> Self {
        let l = sys_locale::get_locale()
            .unwrap_or_default()
            .to_ascii_lowercase();
        if l.starts_with("fr") {
            Lang::Fr
        } else {
            Lang::En
        }
    }

    pub fn t(self) -> &'static Texts {
        match self {
            Lang::En => &EN,
            Lang::Fr => &FR,
        }
    }
}

